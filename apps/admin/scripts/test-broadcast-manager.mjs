import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { chromium, expect } from "playwright/test";

const output = await build({ stdin: { contents: `
  import React from "react"; import { createRoot } from "react-dom/client";
  import { CustomerBroadcastManager } from "./components/customer-broadcast-manager";
  window.calls=[]; window.confirm=()=>true;
  window.fetch=(url, options)=> { window.calls.push({url,...options,body:JSON.parse(options.body)});
    return new Promise((resolve,reject)=> { window.finish=(payload,ok=true)=>resolve({ok,json:async()=>payload}); window.fail=()=>reject(Error("Connection interrupted. Retry this unchanged draft.")); }); };
  createRoot(document.getElementById("root")).render(<CustomerBroadcastManager deals={[]} initialCampaigns={[]}/>);
`, resolveDir: fileURLToPath(new URL("../", import.meta.url)), loader: "tsx" }, bundle: true, write: false, format: "iife", platform: "browser", jsx: "automatic" });
const browser = await chromium.launch({ channel: "chrome", headless: true });
let checks = 0;
const pass = text => { checks++; console.log("PASS " + text); };
try {
  const page = await browser.newPage();
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  await page.route("**/*", route => route.fulfill({ contentType: "text/html", body: '<div id="root"></div>' }));
  await page.goto("https://admin.example.test");
  await page.addScriptTag({ content: output.outputFiles[0].text });
  const send = page.getByRole("button", { name: "Send to all eligible customers" });
  await page.getByLabel("Email subject").fill("Fresh menu");
  await page.getByLabel("Message", { exact: true }).fill("Our new menu is ready.");
  await send.evaluate(button => { button.click(); button.click(); });
  assert.equal(await page.evaluate(() => window.calls.length), 1);
  await expect(page.getByLabel("Email subject")).toBeDisabled();
  const first = await page.evaluate(() => window.calls[0]);
  assert.match(first.body.requestId, /^[0-9a-f-]{36}$/);
  pass("same-frame double click creates one request with an idempotency key and locks draft controls");
  await page.evaluate(() => window.fail());
  await expect(send).toBeEnabled();
  await expect(page.getByRole("status")).toContainText("interrupted");
  await send.click();
  assert.equal(await page.evaluate(() => window.calls[1].body.requestId), first.body.requestId);
  pass("uncertain creation response keeps the draft and reuses the same key on retry");
  await page.evaluate(() => window.finish({ id: "campaign-a", recipientCount: 3 }));
  await expect(page.getByLabel("Email subject")).toHaveValue("");
  await expect.poll(() => page.evaluate(() => window.calls.length)).toBe(3);
  assert.equal(await page.evaluate(() => window.calls[2].method), "PATCH");
  await page.evaluate(() => window.finish({ error: "Could not confirm delivery. Reconcile provider logs before retrying." }, false));
  await expect(send).toBeEnabled();
  await expect(page.getByRole("status")).toContainText("Reconcile");
  await expect(page.getByRole("button", { name: "Resume" })).toHaveCount(1);
  pass("confirmed creation clears draft; failed delivery stays attached to its existing campaign");
  await page.getByRole("button", { name: "Resume" }).evaluate(button => { button.click(); button.click(); });
  assert.equal(await page.evaluate(() => window.calls.length), 4);
  assert.equal(await page.evaluate(() => window.calls[3].body.id), "campaign-a");
  await page.evaluate(() => window.finish({ id: "campaign-a", status: "SENDING", sent: 1, failed: 0, remaining: 2, processed: 0 }));
  await expect(page.getByRole("status")).toContainText("still in progress");
  await expect(send).toBeEnabled();
  assert.equal(await page.evaluate(() => window.calls.length), 4);
  pass("resume uses same campaign; unclaimed in-flight batch stops polling without reporting completed");
  await page.getByRole("button", { name: "Resume" }).click();
  await page.evaluate(() => window.finish({ id: "campaign-a", status: "SENT", sent: 3, failed: 0, remaining: 0, processed: 2 }));
  await expect(page.getByRole("status")).toContainText("sent to 3");
  await expect(page.getByRole("button", { name: "Resume" })).toHaveCount(0);
  pass("completed campaign shows confirmed counts and no resume action");
  await page.getByLabel("Email subject").fill("Fresh menu");
  await page.getByLabel("Message", { exact: true }).fill("Our new menu is ready.");
  await send.click();
  assert.notEqual(await page.evaluate(() => window.calls.at(-1).body.requestId), first.body.requestId);
  await page.evaluate(() => window.finish({ id: "campaign-b", recipientCount: 0 }));
  await expect(page.getByRole("status")).toContainText("No eligible");
  assert.equal(await page.evaluate(() => window.calls.length), 6);
  assert.deepEqual(errors, []);
  pass("intentional new campaign gets a new key; empty audience sends no PATCH and produces a clear outcome");
  console.log(`${checks} browser checks passed. Mock network only; no email sent.`);
} finally { await browser.close(); }
